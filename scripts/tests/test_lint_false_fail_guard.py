def hits_of(text):
    cfg = nl.Config("entertainment", "long", None)
    cfg.finalize()
    _, hits = nl.lint_text(text, cfg, only="CN")
    return [(h["rule"], h["severity"]) for h in hits]


class FalseFailGuard(unittest.TestCase):
    def test_correct_prose_is_never_failed(self):
        for text in MUST_NOT_FAIL:
            fails = [h for h in hits_of(text) if h[1] == "FAIL"]
            self.assertEqual(fails, [], text)

    def test_archetypes_are_still_failed(self):
        for text in MUST_FAIL:
            self.assertTrue(any(h[1] == "FAIL" for h in hits_of(text)), text)

    def test_unresolved_mentions_get_a_verification_notice(self):
        for text in MUST_GUIDE:
            self.assertTrue(any(h[0] in ("C01", "C03", "C07") for h in hits_of(text)), text)

    def test_mismatches_are_not_silently_passed(self):
        for text in MUST_REPORT:
            self.assertTrue(any(h[0] in ("C01", "C03") for h in hits_of(text)), text)


